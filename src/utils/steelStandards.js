export function getUnitWeight(sizeStr, defaultWeight = 0) {
  if (!sizeStr) return defaultWeight;
  const clean = sizeStr.trim();
  if (UNIT_WEIGHT_LOOKUP[clean] !== undefined) return UNIT_WEIGHT_LOOKUP[clean];
  
  // Case-insensitive match or contains
  const lower = clean.toLowerCase();
  for (const [key, val] of Object.entries(UNIT_WEIGHT_LOOKUP)) {
    if (key.toLowerCase() === lower || lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      return val;
    }
  }
  return defaultWeight;
}
